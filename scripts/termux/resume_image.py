"""Verify restored Docker filesystem inputs before reusing its compiled cache."""
import hashlib
import json
from pathlib import Path, PurePosixPath
import shlex
import subprocess
import tarfile

HOME = '/home/builder'
REPO = HOME + '/termux-packages'
ENTRYPOINT = ['/bin/bash', HOME + '/build-in-container.sh']


def destination(value):
    p = PurePosixPath(value)
    if not p.is_absolute() or '..' in p.parts or not p.is_relative_to(HOME):
        raise ValueError('Resume input path escapes builder home')
    return p.as_posix()


def record_file(path):
    if path.is_symlink():
        return dict(kind='link', target=path.readlink().as_posix())
    if not path.is_file():
        raise ValueError('Resume COPY requires ordinary files or symlinks')
    with path.open('rb') as stream:
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    return dict(kind='file', size=path.stat().st_size, sha256=digest)


def expected_inputs(context):
    """Interpret only the fixed Dockerfile generated by prepare.py/seed.py.

    Unknown instructions fail closed. Match the source ADD, overlay/COPY order
    and explicit deletions instead of treating the image's label as file proof.
    """
    context = Path(context)
    records, absent = {}, set()
    source_seen = entry_seen = workdir_seen = False
    for line in (context / 'Dockerfile').read_text().splitlines():
        if line.startswith('FROM ') or line in ('USER root', 'USER builder'):
            continue
        if line == 'ADD --chown=builder:builder source.tar ' + REPO + '/':
            if source_seen:
                raise ValueError('Duplicate resume source archive')
            source_seen = True
            with tarfile.open(context / 'source.tar') as archive:
                for member in archive:
                    name = PurePosixPath(member.name)
                    if name.is_absolute() or '..' in name.parts:
                        raise ValueError('Resume source archive path escapes')
                    target = destination(REPO + '/' + name.as_posix())
                    if member.isdir():
                        continue
                    if member.issym():
                        records[target] = dict(kind='link', target=PurePosixPath(member.linkname).as_posix())
                    elif member.isfile():
                        with archive.extractfile(member) as stream:
                            digest = hashlib.file_digest(stream, 'sha256').hexdigest()
                        records[target] = dict(kind='file', size=member.size, sha256=digest)
                    else:
                        raise ValueError('Unsupported resume source archive member')
            continue
        if line.startswith('COPY --chown=builder:builder '):
            words = shlex.split(line)
            target = destination(words[-1])
            for source in words[2:-1]:
                name = PurePosixPath(source)
                if name.is_absolute() or '..' in name.parts:
                    raise ValueError('Resume COPY path escapes context')
                path = context / source
                if source.endswith('/'):
                    if path.is_symlink() or not path.is_dir():
                        raise ValueError('Resume COPY requires a real directory')
                    for file in sorted(path.rglob('*')):
                        if file.is_symlink() or file.is_file():
                            dest = destination(target + '/' + file.relative_to(path).as_posix())
                            records[dest] = record_file(file)
                            absent.discard(dest)
                else:
                    dest = destination(target + '/' + name.name)
                    records[dest] = record_file(path)
                    absent.discard(dest)
            continue
        if line.startswith('RUN rm -- '):
            for target in shlex.split(line)[3:]:
                target = destination(target)
                if not target.startswith(REPO + '/packages/lrzsz/'):
                    raise ValueError('Unexpected resume source deletion')
                records.pop(target, None)
                absent.add(target)
            continue
        if line == 'RUN find ' + REPO + ' -name "*.sh" -exec chmod u+x {} +':
            continue
        if line == 'WORKDIR ' + REPO:
            workdir_seen = True
            continue
        if line.startswith('ENTRYPOINT ') and json.loads(line[11:]) == ENTRYPOINT:
            entry_seen = True
            continue
        raise ValueError('Unsupported resume Dockerfile instruction')
    if not source_seen or not entry_seen or not workdir_seen or not records:
        raise ValueError('Incomplete resume input specification')
    return dict(schema=1, files=records, absent=sorted(absent))


# Runs inside a network-disabled, unprivileged, memory/CPU-bounded probe.
# It reads only expected builder inputs, never writes the checkpoint filesystem.
VERIFY = r'''
import hashlib,json,pathlib,sys
data=json.load(sys.stdin)
assert data['schema']==1 and len(data['files'])<=200000
home=pathlib.Path('/home/builder')
assert home.resolve()==home
for name,expected in data['files'].items():
 p=pathlib.Path(name)
 assert p.is_absolute() and p.is_relative_to(home) and '..'not in p.parts
 assert p.parent.resolve()==p.parent, 'Cached input parent symlink: '+name
 if expected['kind']=='link':
  assert p.is_symlink() and p.readlink().as_posix()==expected['target'], 'Cached input link differs: '+name
 else:
  assert not p.is_symlink() and p.is_file() and p.stat().st_size==expected['size'], 'Cached input differs: '+name
  with p.open('rb')as f: actual=hashlib.file_digest(f,'sha256').hexdigest()
  assert actual==expected['sha256'], 'Cached input digest differs: '+name
for name in data['absent']:
 p=pathlib.Path(name)
 assert p.is_relative_to(home) and '..'not in p.parts
 assert not p.exists()and not p.is_symlink(), 'Removed cached input reappeared: '+name
print(json.dumps({'verified_files':len(data['files']),'verified_absent':len(data['absent'])}))
'''


def verify_restored_inputs(image, context, proof_path):
    manifest = expected_inputs(context)
    raw = json.dumps(manifest, sort_keys=True).encode()
    if len(raw) > 32 * 1024**2:
        raise ValueError('Resume input manifest exceeds limit')
    result = subprocess.run([
        'docker', 'run', '--rm', '--read-only', '--cap-drop', 'ALL', '--network', 'none', '--cpus', '1',
        '--memory', '512m', '--pids-limit', '64', '--security-opt', 'no-new-privileges',
        '--user', 'builder', '--workdir', REPO, '-i', '--entrypoint', 'python3',
        image, '-c', VERIFY], input=raw, capture_output=True, timeout=300, check=True)
    verified = json.loads(result.stdout)
    if verified != dict(verified_files=len(manifest['files']), verified_absent=len(manifest['absent'])):
        raise ValueError('Unexpected restored input verification result')
    proof = dict(image=image, manifest_sha256=hashlib.sha256(raw).hexdigest(), **verified)
    Path(proof_path).write_text(json.dumps(proof, indent=2) + '\n')
    print('Restored filesystem inputs verified; reuse image without rebuilding/exporting it', flush=True)
